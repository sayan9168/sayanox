def sx_str(s: str) -> str:
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def sx_list(xs) -> str:
    return "[" + ", ".join(str(int(x)) for x in xs) + "]"


class Gen:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.want: list[str] = []
        self.counter = 0
        self.negs: dict[int, str] = {}
        self.sec_open = False
        self.sec_counter = 0
        self.sections: list[str] = []

    def name(self, prefix: str) -> str:
        self.counter += 1
        return f"lp_{prefix}_{self.counter}"

    def numlit(self, v: int) -> str:
        v = int(v)
        if v >= 0:
            return str(v)
        if v == -1:
            return "lp_n1()"
        if v not in self.negs:
            name = self.name("neg")
            self.lines.append(f"hold {name} = 0 - {-v}")
            self.negs[v] = name
        return self.negs[v]

    def num(self, expr: str, value: int) -> None:
        self.lines.append(f"show lp_num({expr})")
        self.want.append(str(int(value)))

    def text(self, expr: str, value: str) -> None:
        self.lines.append(f"show {expr}")
        self.want.append(value)

    def lst(self, expr: str, values) -> None:
        self.lines.append(f"show lp_list({expr})")
        self.want.append(",".join(str(int(x)) for x in values))

    def hold(self, expr: str) -> str:
        name = self.name("h")
        self.lines.append(f"hold {name} = {expr}")
        return name

    def section(self, title: str) -> None:
        if self.sec_open:
            self.lines.append("  give 0")
            self.lines.append("}")
        self.sec_counter += 1
        name = f"lp_sec_{self.sec_counter}"
        self.sections.append(name)
        self.sec_open = True
        self.lines.append("")
        self.lines.append(f"// ---- {title} ----")
        self.lines.append(f"make {name}() -> num {{")


