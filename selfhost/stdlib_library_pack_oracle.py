def canon(d: Decimal) -> str:
    s = format(d, "f")
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s

def fixed(d: Decimal, places: int) -> str:
    q = d.quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP)
    s = format(q, "f")
    if places == 0:
        return s
    if "." not in s:
        s += "."
    if len(s.split(".")[1]) < places:
        s += "0" * (places - len(s.split(".")[1]))
    return s

def allocate(total: str, weights: list[int], places: int):
    x = Decimal(total)
    if x < 0 or x != x.quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP):
        return None
    if not weights or any(w < 0 for w in weights) or sum(weights) == 0:
        return None
    units = int(x.scaleb(places))
    sw = sum(weights)
    qs = [units * w // sw for w in weights]
    rs = [units * w % sw for w in weights]
    left = units - sum(qs)
    order = sorted(range(len(weights)), key=lambda i: (-rs[i], i))
    for i in order[:left]:
        qs[i] += 1
    return [fixed(Decimal(q).scaleb(-places), places) for q in qs]

