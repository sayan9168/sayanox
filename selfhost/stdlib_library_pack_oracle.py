def begin_module(name: str, uses: list[str]) -> Gen:
    gg = Gen()
    gg.lines.append(f"// Generated by selfhost/stdlib_library_pack_oracle.py; do not edit by hand.")
    gg.lines.append(f"// Independent Python oracle for library-pack module group: {name}.")
    for u in uses:
        gg.lines.append(f'use "{u}"')
    gg.lines.append("")
    gg.lines.extend(HELPERS.splitlines())
    gg.lines.append("")
    gg.lines.append("make lp_n1() -> num {")
    gg.lines.append("  give 0 - 1")
    gg.lines.append("}")
    return gg


def finish_module(gg: Gen, name: str) -> None:
    if gg.sec_open:
        gg.lines.append("  give 0")
        gg.lines.append("}")
        gg.sec_open = False
    gg.lines.append("")
    gg.lines.append("make main_lp() -> num {")
    for i, sec in enumerate(gg.sections, 1):
        gg.lines.append(f"  hold call_{i} = {sec}()")
    sentinel = f"library-pack-{name}-ok"
    gg.lines.append(f'  show "{sentinel}"')
    gg.want.append(sentinel)
    gg.lines.append("  give 0")
    gg.lines.append("}")
    gg.lines.append("")
    gg.lines.append("hold run_lp = main_lp()")
    sa = ROOT / f"selfhost/stdlib_library_pack_{name}_test.sa"
    want = ROOT / f"selfhost/stdlib_library_pack_{name}.want"
    sa.write_text("\n".join(gg.lines) + "\n")
    want.write_text("\n".join(gg.want) + "\n")
    print(f"wrote {sa.name} ({len(gg.lines)} lines) and {want.name} ({len(gg.want)} checks)")


