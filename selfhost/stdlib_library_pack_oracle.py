def graph_expr(n: int, directed: int, edges) -> str:
    expr = f"gr_new({n}, {directed})"
    for u, v, w in edges:
        expr = f"gr_add_edge({expr}, {u}, {v}, {w})"
    return expr

def gr_bfs(n, directed, edges, src):
    dist = [-1] * n
    dist[src] = 0
    queue = [src]
    head = 0
    while head < len(queue):
        v = queue[head]
        head += 1
        for u, t, _w in edges:
            to = None
            if u == v:
                to = t
            if directed == 0 and t == v:
                to = u
            if to is not None and dist[to] < 0:
                dist[to] = dist[v] + 1
                queue.append(to)
    return dist

def gr_dist(n, directed, edges, src):
    inf = float("inf")
    dist = [inf] * n
    dist[src] = 0
    visited = [False] * n
    for _ in range(n):
        best = None
        for v in range(n):
            if not visited[v] and dist[v] < inf and (best is None or dist[v] < dist[best]):
                best = v
        if best is None:
            break
        visited[best] = True
        for u, t, w in edges:
            to = None
            if u == best:
                to = t
            if directed == 0 and t == best:
                to = u
            if to is not None and dist[best] + w < dist[to]:
                dist[to] = dist[best] + w
    return [-1 if d == inf else int(d) for d in dist]

def gr_components(n, edges):
    labels = [-1] * n
    comp = 0
    for start in range(n):
        if labels[start] >= 0:
            continue
        labels[start] = comp
        queue = [start]
        head = 0
        while head < len(queue):
            v = queue[head]
            head += 1
            for u, t, _w in edges:
                to = None
                if u == v:
                    to = t
                if t == v:
                    to = u
                if to is not None and labels[to] < 0:
                    labels[to] = comp
                    queue.append(to)
        comp += 1
    return labels

def gr_toposort(n, edges):
    indeg = [0] * n
    for _u, v, _w in edges:
        indeg[v] += 1
    queue = [v for v in range(n) if indeg[v] == 0]
    order = []
    head = 0
    while head < len(queue):
        v = queue[head]
        head += 1
        order.append(v)
        for u, t, _w in edges:
            if u == v:
                indeg[t] -= 1
                if indeg[t] == 0:
                    queue.append(t)
    return order if len(order) == n else None

