def tw_normalize(s: str) -> str:
    return " ".join(s.split())

def tw_wrap(s: str, width: int) -> str:
    text = tw_normalize(s)
    if not text:
        return ""
    out = []
    line = ""
    for word in text.split(" "):
        if not line:
            while len(word) > width:
                out.append(word[:width])
                word = word[width:]
            line = word
        else:
            if len(line) + 1 + len(word) <= width:
                line += " " + word
            else:
                out.append(line)
                line = ""
                while len(word) > width:
                    out.append(word[:width])
                    word = word[width:]
                line = word
    if line:
        out.append(line)
    return "\n".join(out)

